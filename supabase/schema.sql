create or replace function public.set_active_gateway(p_provider text, p_active boolean)
returns void language plpgsql security invoker set search_path = ''
as $$
begin
  if not exists (select 1 from public.admin_users where user_id = (select auth.uid())) then
    raise exception 'Acesso administrativo não autorizado';
  end if;
  if p_provider not in ('primecash', 'titans') then raise exception 'Gateway inválido'; end if;
  if p_active then
    update public.gateway_settings set active = false, updated_at = now() where provider <> p_provider and active;
  end if;
  update public.gateway_settings set active = p_active, updated_at = now() where provider = p_provider;
end;
$$;

create or replace function public.set_primecash_secret(p_secret text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  secret_id uuid;
begin
  if p_secret is null or char_length(trim(p_secret)) < 12 or char_length(p_secret) > 500 then
    raise exception 'Secret Key inválida';
  end if;
  select id into secret_id from vault.secrets where name = 'primecash_secret_key';
  if secret_id is null then
    perform vault.create_secret(trim(p_secret), 'primecash_secret_key', 'PrimeCash API Secret Key');
  else
    perform vault.update_secret(secret_id, trim(p_secret), 'primecash_secret_key', 'PrimeCash API Secret Key');
  end if;
end;
$$;


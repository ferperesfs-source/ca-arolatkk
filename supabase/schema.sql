create or replace function public.set_marketing_secret(p_integration_id uuid, p_secret text)
returns void language plpgsql security definer set search_path = ''
as $$
declare secret_id uuid;
declare secret_name text := 'marketing_integration_' || p_integration_id::text;
begin
  if p_secret is null or char_length(trim(p_secret)) < 8 or char_length(p_secret) > 1000 then raise exception 'Credencial de rastreamento inválida'; end if;
  if not exists (select 1 from public.marketing_integrations where id = p_integration_id) then raise exception 'Integração não encontrada'; end if;
  select id into secret_id from vault.secrets where name = secret_name;
  if secret_id is null then perform vault.create_secret(trim(p_secret), secret_name, 'Credencial server-side de rastreamento');
  else perform vault.update_secret(secret_id, trim(p_secret), secret_name, 'Credencial server-side de rastreamento'); end if;
end;
$$;
create or replace function public.get_marketing_secret(p_integration_id uuid) returns text language sql stable security definer set search_path = '' as $$ select decrypted_secret from vault.decrypted_secrets where name = 'marketing_integration_' || p_integration_id::text limit 1; $$;
create or replace function public.delete_marketing_secret(p_integration_id uuid) returns void language plpgsql security definer set search_path = '' as $$ declare secret_id uuid; begin select id into secret_id from vault.secrets where name = 'marketing_integration_' || p_integration_id::text; if secret_id is not null then delete from vault.secrets where id = secret_id; end if; end; $$;
create or replace function public.claim_marketing_delivery(p_order_id bigint, p_integration_id uuid) returns bigint language plpgsql security definer set search_path = '' as $$ declare delivery_id bigint; begin insert into public.marketing_deliveries (order_id, integration_id, event_name, status) values (p_order_id, p_integration_id, 'purchase', 'processing') on conflict (order_id, integration_id, event_name) do update set status = 'processing', response_status = null, last_error = null, updated_at = now() where public.marketing_deliveries.status = 'failed' returning id into delivery_id; return delivery_id; end; $$;
